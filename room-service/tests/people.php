 INSERT INTO rooms VALUES('aaaaaaaaaaaaaaaa','Familie','1111111111111111'),('bbbbbbbbbbbbbbbb','Kontaktgespräch','1111111111111111');
 INSERT INTO members VALUES('aaaaaaaaaaaaaaaa','1111111111111111'),('aaaaaaaaaaaaaaaa','2222222222222222'),('aaaaaaaaaaaaaaaa','3333333333333333'),('bbbbbbbbbbbbbbbb','1111111111111111'),('bbbbbbbbbbbbbbbb','2222222222222222');
 INSERT INTO direct_rooms VALUES('bbbbbbbbbbbbbbbb','1111111111111111','2222222222222222');");
$migrated=new Rooms($legacy,$mail,'https://peekaview.de');
$old=['id'=>'1111111111111111','email'=>'old@example.test','name'=>'Alter Computer','platform'=>'desktop'];
$state=$migrated->state($old);
check(count($state['contacts'])===1 && count($state['contacts'][0]['devices'])===2,'Legacy device contacts merge into one person');
check(count($state['rooms'])===1 && count($state['rooms'][0]['people'])===2,'Legacy groups retain their people without showing direct rooms');
$oldCall=$migrated->mutate($old,'calls/direct',['person'=>$state['contacts'][0]['id']]);
check($legacy->query("SELECT room FROM calls WHERE id='".$oldCall['id']."'")->fetchColumn()==='bbbbbbbbbbbbbbbb','Legacy direct room is reused for the person');
$legacy->exec("DELETE FROM rooms WHERE id='aaaaaaaaaaaaaaaa'");
check(count($migrated->state($old)['contacts'])===1,'Legacy direct contacts remain known without a shared group');
