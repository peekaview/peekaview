<?php
declare(strict_types=1);
require dirname(__DIR__).'/Rooms.php';
use PeekaView\Rooms;
use PeekaView\Problem;

$checks=0;$outbox=[];$db=new PDO('sqlite::memory:');
function check(bool $ok,string $message):void {global $checks;++$checks;if(!$ok)throw new RuntimeException($message);}
function denied(callable $run,int $status):void {try{$run();throw new RuntimeException('Expected denial');}catch(Problem $e){check($e->status===$status,$e->getMessage());}}
$mail=function($to,$subject,$body)use(&$outbox){preg_match('/invite=([^&\s]+)/',$body,$m);$outbox[]=['to'=>$to,'token'=>$m[1],'body'=>$body];};
$service=new Rooms($db,$mail,'https://peekaview.de');
function register(Rooms $service,string $email,string $name):array {
    global $outbox;
    $service->requestDevice(['email'=>$email,'_api'=>'https://rooms.example.test/api.php','next_action'=>'contact']);
    return $service->accept(['invitation'=>end($outbox)['token'],'name'=>$name,'platform'=>'browser'],null);
}
$a=register($service,'anna@example.test','Laptop');$a2=register($service,'anna@example.test','Handy');
$b=register($service,'ben@example.test','Computer');$b2=register($service,'ben@example.test','Telefon');
$ad=$a['device'];$bd=$b['device'];
check($a['next_action']==='contact','The email link resumes the intended action');
check($service->state($ad)['contacts']===[],'Own devices are not contacts');
check($a['token']!==$a2['token'],'Devices keep separate credentials');
$profile=$service->state($ad)['person'];
check(count($profile['devices'])===2 && array_column($profile['devices'],'id')===[$a2['device']['id'],$ad['id']],'Own profile lists all own devices and no other person’s devices');
check(array_keys($profile['devices'][0])===['id','name','platform'],'Profile contains device labels, never credentials');
$service->mutate($ad,'contacts/invite',['email'=>$bd['email'],'_api'=>'https://rooms.example.test/api.php']);
$invite=end($outbox)['token'];$preview=$service->preview($invite);
check($preview['kind']==='contact' && $preview['sender_email']===$ad['email'],'Contact invitation names its sender and purpose');
check($service->state($ad)['invitations'][0]['email']===$bd['email'],'Pending invitation is visible');
denied(fn()=>$service->accept(['invitation'=>$invite,'name'=>'Wrong','platform'=>'browser'],$ad),403);
$service->accept(['invitation'=>$invite,'name'=>'Computer','platform'=>'browser'],$bd);
denied(fn()=>$service->accept(['invitation'=>$invite,'name'=>'Again','platform'=>'browser'],$bd),410);
$ben=$service->state($ad)['contacts'][0];$anna=$service->state($bd)['contacts'][0];
check($ben['name']==='ben' && count($ben['devices'])===2,'One person contains both devices in details');
check(count($service->state($ad)['contacts'])===1 && count($service->state($b2['device'])['contacts'])===1,'Relationship belongs to people on both sides');
check(count($service->state($ad,1)['contacts'])===2 && $service->state($ad,1)['contacts'][0]['id']!==$ben['id'],'Published v1 clients retain their device-based response contract');
check($service->state($ad)['rooms']===[] && $service->state($bd)['rooms']===[],'Direct invitation never creates a visible group');
check($service->state($ad)['invitations']===[],'Accepted invitation is no longer pending');
denied(fn()=>$service->mutate($ad,'contacts/invite',['email'=>$ad['email'],'_api'=>'https://rooms.example.test/api.php']),400);
$call=$service->mutate($ad,'calls/direct',['person'=>$ben['id']])['id'];
check($service->state($bd)['calls'][0]['status']==='ringing' && $service->state($b2['device'])['calls'][0]['status']==='ringing','All devices of the called person ring');
check($service->state($a2['device'])['calls']===[],'Caller does not call their own other devices');
check(!isset($service->state($bd)['calls'][0]['secret']),'Ringing devices have no conversation secret');
$db->prepare('INSERT INTO push(device,subscription) VALUES(?,?)')->execute([$bd['id'],'{}']);
$answer=$service->mutate($b2['device'],'calls/join',['call'=>$call]);
check($answer['answered_call']===$call && count($service->pushTargets($call,null,false,$bd['email']))===1,'Answered push targets only the other ringing devices of this person');
check($service->state($bd)['calls']===[],'First answer removes ringing on the other device');
denied(fn()=>$service->mutate($bd,'calls/join',['call'=>$call]),409);
denied(fn()=>$service->mutate($bd,'calls/direct',['person'=>$anna['id']]),409);
check(count($service->state($ad)['calls'][0]['participants'])===2,'Only the accepted device is admitted');
$service->mutate($ad,'calls/leave',['call'=>$call]);$service->mutate($b2['device'],'calls/leave',['call'=>$call]);
$group=$service->mutate($ad,'rooms/create',['name'=>'Familie','people'=>[$ben['id']]])['id'];
$room=$service->state($a2['device'])['rooms'][0];
check(count($room['people'])===2 && count($room['participants'])===4,'Group counts people and retains individual device membership');
check($room['can_manage'],'Group owner can manage from another verified device');
$service->mutate($ad,'rooms/settings',['room'=>$group,'pin_enabled'=>true,'pin'=>'Test!6']);
$service->mutate($bd,'rooms/access',['room'=>$group,'unattended'=>true]);
check(!$service->state($b2['device'])['rooms'][0]['unattended'],'Capture policy is never inherited by a sibling device');
$b3=register($service,'ben@example.test','Drittes Gerät');
check(count($service->state($b3['device'])['rooms'])===1,'New email-confirmed device sees the person’s groups');
check(count($service->state($ad)['contacts'][0]['devices'])===3,'New verified device appears under the existing person');
check(!$service->state($b3['device'])['rooms'][0]['unattended'],'New device has no unattended capture permission');
$call=$service->mutate($ad,'calls/start',['room'=>$group,'pin'=>'Test!6'])['id'];
$a3=register($service,'anna@example.test','Neuer Computer');
$pending=$service->state($a3['device'])['calls'][0];
check($pending['status']==='requested' && !isset($pending['secret']),'New devices still need admission to a running share');
denied(fn()=>$service->mutate($a3['device'],'calls/start',['room'=>$group,'pin'=>'Test!6']),403);
$c=register($service,'carla@example.test','Carlas Telefon');
$service->mutate($ad,'contacts/invite',['email'=>$c['device']['email'],'_api'=>'https://rooms.example.test/api.php']);
$service->accept(['invitation'=>end($outbox)['token'],'name'=>'Carlas Telefon','platform'=>'browser'],$c['device']);
$carla=array_values(array_filter($service->state($ad)['contacts'],fn($p)=>$p['email']===$c['device']['email']))[0];
$added=$service->mutate($ad,'rooms/add-contact',['room'=>$group,'person'=>$carla['id']]);
check($added['notify_call']===$call,'Adding a new person rings them in the running group');
check($service->state($c['device'])['calls'][0]['status']==='ringing' && !isset($service->state($c['device'])['calls'][0]['secret']),'Explicitly added people still accept before receiving media');
$ids=array_column($service->state($ad)['contacts'],'id');
$service=new Rooms($db,$mail,'https://peekaview.de');
check(array_column($service->state($ad)['contacts'],'id')===$ids,'Repeated schema migration preserves person IDs');
check($service->device($a['token'])===$ad,'Migration preserves existing device tokens');
$legacy=new PDO('sqlite::memory:');
$legacy->exec("CREATE TABLE devices(id TEXT PRIMARY KEY,email TEXT,name TEXT,platform TEXT,token_hash TEXT,seen INTEGER);
 CREATE TABLE rooms(id TEXT PRIMARY KEY,name TEXT,owner TEXT);
